    HDrtwi_point(:,shock_comm) ...
    HDrtwi_point(:,shock_vix) ...
    HDrtwi_point(:,shock_augdp) ...
        + HDrtwi_point(:,shock_inf) ...
    HDrtwi_point(:,shock_spread) ...
    HDrtwi_point(:,shock_er)];


%% ================================================================
% 11. EPISODE POINT CONTRIBUTIONS
%% ================================================================

PointContrib = ...
    nan(nEpisodes,nComponents);


PointError = ...
    nan(nEpisodes,1);


for ee = 1:nEpisodes

    i0 = ...
        episode_i0(ee);


    i1 = ...
        episode_i1(ee);


    PointContrib(ee,1) = ...
        baseline_point(i1,shock_er) ...
        - baseline_point(i0,shock_er);


    PointContrib(ee,2:7) = ...
        HD_grouped_point(i1,:) ...
        - HD_grouped_point(i0,:);


    PointError(ee) = ...
        ActualChange(ee) ...
        - sum(PointContrib(ee,:));

end


