%  Selected episodes:
%
%       GFC
%       Commodity-boom appreciation
%       Post-boom depreciation
%       COVID shock
%       COVID rebound
%       2022Q1-2026Q2
%       2025Q4-2026Q2
%
%  Components remain separate:
%
%       Global activity
%       Commodity prices
%       Global risk / VIX
%       Domestic macro
%       Relative yields
%       Other exchange-rate shocks
%
%% ================================================================

clear;
clc;
close all;


%% ================================================================
% 1. PATHS
%% ================================================================

folder = ...
    fileparts(mfilename('fullpath'));


addpath(fullfile(folder,'_func'));


