    length(componentNames);


CI70 = ...
    [0.15 0.85];


CI95 = ...
    [0.025 0.975];


%% ================================================================
% PART A
% POSTERIOR-MEAN-MODEL POINT DECOMPOSITION
%% ================================================================

%% 8. POSTERIOR-MEAN PARAMETERS

