    fullfile( ...
        resultDir, ...
        'bvar_soe_baseline_lambda020_stable.mat');


assert(isfile(BVARfile));

assert( ...
    exist('historical_decomposition','file') == 2);


%% ================================================================
% 2. LOAD FINAL BVAR
%% ================================================================

S = ...
    load(BVARfile);


BVAR = ...
    S.BVAR;


clear S


y = ...
    BVAR.y;


[T,N] = ...
    size(y);


p = ...
    BVAR.p;


nDraws = ...
    size(BVAR.phi_draws,3);


assert(N == 7);

assert(p == 2);

assert(~isempty(BVAR.e_draws));


fprintf('\n');
fprintf('============================================================\n');
fprintf('FINAL BVAR HISTORICAL DECOMPOSITION\n');
fprintf('============================================================\n');

fprintf('Posterior draws: %d\n',nDraws);


%% ================================================================
% 3. SHOCK POSITIONS
%% ================================================================

shock_us = 1;

shock_comm = 2;

shock_vix = 3;

shock_augdp = 4;

shock_inf = 5;

shock_spread = 6;

shock_er = 7;


%% ================================================================
% 4. LOAD DATES
%% ================================================================

data = readtable( ...
    dataFile, ...
    'Sheet','data', ...
    'VariableNamingRule','preserve');


data = standardizeMissing( ...
    data, ...
    {'NA','N/A','na',''});


if ~isdatetime(data.quarter_start)

    if isnumeric(data.quarter_start)

        data.quarter_start = ...
            datetime( ...
                data.quarter_start, ...
                'ConvertFrom','excel');

    else

        data.quarter_start = ...
            datetime(data.quarter_start);

    end

end


sample = ...
    data.quarter_start >= datetime(1995,1,1) ...
    & data.quarter_start <= datetime(2026,4,1);


D = ...
    data(sample,:);


assert(height(D) == T);


%% ================================================================
% 5. FINAL EPISODES
%% ================================================================

episodeNames = { ...
    'GFC', ...
    'Commodity-boom appreciation', ...
    'Post-boom depreciation', ...
    'COVID shock', ...
    'COVID rebound', ...
    '2022Q1-2026Q2', ...
    '2025Q4-2026Q2'};


plotLabels = { ...
    'GFC', ...
    'Commodity boom', ...
    'Post-boom', ...
    'COVID shock', ...
    'COVID rebound', ...
    '2022-26', ...
    'Late-2025-26'};


episodeStart = [ ...
    datetime(2008,7,1); ...
    datetime(2009,7,1); ...
    datetime(2013,1,1); ...
    datetime(2020,1,1); ...
    datetime(2020,4,1); ...
    datetime(2022,1,1); ...
    datetime(2025,10,1)];


episodeEnd = [ ...
    datetime(2009,4,1); ...
    datetime(2011,4,1); ...
    datetime(2015,7,1); ...
    datetime(2020,1,1); ...
    datetime(2021,4,1); ...
    datetime(2026,4,1); ...
    datetime(2026,4,1)];


nEpisodes = ...
    length(episodeNames);


%% ================================================================
% 6. EPISODE INDICES
%% ================================================================

episode_i0 = ...
    nan(nEpisodes,1);


episode_i1 = ...
    nan(nEpisodes,1);


ActualChange = ...
    nan(nEpisodes,1);


for ee = 1:nEpisodes

    episode_i0(ee) = ...
        find( ...
            D.quarter_start < episodeStart(ee), ...
            1, ...
            'last');


    episode_i1(ee) = ...
        find( ...
            D.quarter_start <= episodeEnd(ee), ...
            1, ...
            'last');


    assert( ...
        ~isempty(episode_i0(ee)) ...
        && ~isempty(episode_i1(ee)));


    ActualChange(ee) = ...
        y(episode_i1(ee),shock_er) ...
        - y(episode_i0(ee),shock_er);

end


%% ================================================================
% 7. COMPONENT NAMES
%% ================================================================

