%% ================================================================
% LOCAL FUNCTION
%% ================================================================

function baseline = ...
    constructVARBaseline( ...
    phi, ...
    y, ...
    p)

% ================================================================
% Construct no-shock VAR baseline.
%
% Uses the same mean-backcasting convention used in our BVAR work.
%% ================================================================

    [T,N] = ...
        size(y);


    initialMean = ...
        mean(y,1);


    baseline_ext = [ ...
        repmat(initialMean,p,1); ...
        zeros(T,N)];


    for t = 1:T

        thisValue = ...
            phi(1,:);


        for lag = 1:p

            rows = ...
                2 + (lag-1)*N : ...
                1 + lag*N;


            thisValue = ...
                thisValue ...
                + baseline_ext(p+t-lag,:) ...
                * phi(rows,:);

        end


        baseline_ext(p+t,:) = ...
            thisValue;

    end


    baseline = ...
        baseline_ext(p+1:end,:);

end