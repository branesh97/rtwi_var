%% ================================================================
%  RECENT AUSTRALIAN DOLLAR APPRECIATION
%  SOE-BVAR HISTORICAL DECOMPOSITION
%
%  Episode:
%
%       2025Q4 to 2026Q2
%
%  Change is measured from:
%
%       2025Q3 to 2026Q2
%
%  so the episode contains:
%
%       2025Q4
%       2026Q1
%       2026Q2
%
%  Outputs:
%
%   1. Posterior-mean-model point decomposition
%   2. Posterior median contributions
%   3. 70% credible intervals
%   4. 95% credible intervals
%   5. Ordering-robust grouped channels
%
%  Uses final locked SOE-BVAR:
%
%       lambda = 0.20
%       p = 2
%       stable-only posterior
%       10,000 retained draws
%% ================================================================

clear;
clc;
close all;


%% ================================================================
% 1. PATHS
%% ================================================================

folder = ...
    fileparts(mfilename('fullpath'));


addpath(fullfile(folder,'_func'));


resultDir = ...
    fullfile(folder,'results');


figDir = ...
    fullfile(folder,'figures');


if ~exist(figDir,'dir')
    mkdir(figDir);
end


dataFile = ...
    fullfile( ...
        folder, ...
        'data', ...
        'data_collected.xlsx');


BVARfile = ...
    fullfile( ...
        resultDir, ...
        'bvar_soe_baseline_lambda020_stable.mat');


assert( ...
    isfile(BVARfile), ...
    'Final BVAR file not found.');


assert( ...
    exist('historical_decomposition','file') == 2, ...
    'historical_decomposition.m not found.');


%% ================================================================
% 2. LOAD FINAL BVAR
%% ================================================================

S = ...
    load(BVARfile);


BVAR = ...
    S.BVAR;


clear S


y = ...
    BVAR.y;


[T,N] = ...
    size(y);


p = ...
    BVAR.p;


nDraws = ...
    size(BVAR.phi_draws,3);


assert(N == 7);

assert(p == 2);


assert( ...
    ~isempty(BVAR.e_draws), ...
    'BVAR residual draws were not stored.');


fprintf('\n');
fprintf('============================================================\n');
fprintf('BVAR: RECENT APPRECIATION HISTORICAL DECOMPOSITION\n');
fprintf('============================================================\n');

fprintf('Posterior draws: %d\n',nDraws);


%% ================================================================
% 3. VARIABLE / SHOCK POSITIONS
%% ================================================================

shock_us = 1;

shock_comm = 2;

shock_vix = 3;

shock_augdp = 4;

shock_inf = 5;

shock_spread = 6;

shock_er = 7;


%% ================================================================
% 4. IMPORT DATES
%% ================================================================

data = readtable( ...
    dataFile, ...
    'Sheet','data', ...
    'VariableNamingRule','preserve');


data = standardizeMissing( ...
    data, ...
    {'NA','N/A','na',''});


if ~isdatetime(data.quarter_start)

    if isnumeric(data.quarter_start)

        data.quarter_start = ...
            datetime( ...
                data.quarter_start, ...
                'ConvertFrom','excel');

    else

        data.quarter_start = ...
            datetime(data.quarter_start);

    end

end


%% ================================================================
% 5. MATCH BVAR SAMPLE
%% ================================================================

sample = ...
    data.quarter_start >= datetime(1995,1,1) ...
    & data.quarter_start <= datetime(2026,4,1);


D = ...
    data(sample,:);


assert( ...
    height(D) == T, ...
    'Data dates do not match BVAR sample.');


%% ================================================================
% 6. DEFINE RECENT APPRECIATION EPISODE
%% ================================================================

episodeName = ...
    '2025Q4-2026Q2';


episodeStart = ...
    datetime(2025,10,1);


episodeEnd = ...
    datetime(2026,4,1);


% Quarter immediately BEFORE episode starts:
%
% 2025Q3

i0 = ...
    find( ...
        D.quarter_start < episodeStart, ...
        1, ...
        'last');


% Final quarter:
%
% 2026Q2

i1 = ...
    find( ...
        D.quarter_start <= episodeEnd, ...
        1, ...
        'last');


assert( ...
    ~isempty(i0) && ~isempty(i1));


fprintf('\nEpisode: %s\n',episodeName);

fprintf( ...
    'Change measured from %s to %s\n', ...
    string(D.quarter_start(i0)), ...
    string(D.quarter_start(i1)));


%% ================================================================
% 7. OBSERVED RTWI CHANGE
%% ================================================================

ActualChange = ...
    y(i1,shock_er) ...
    - y(i0,shock_er);


fprintf( ...
    'Observed RTWI change: %.4f log points\n', ...
    ActualChange);


%% ================================================================
% 8. CREDIBLE INTERVAL SETTINGS
%% ================================================================

CI70 = ...
    [0.15 0.85];


CI95 = ...
    [0.025 0.975];


%% ================================================================
% PART A
% POSTERIOR-MEAN-MODEL POINT DECOMPOSITION
%% ================================================================

%% 9. POSTERIOR-MEAN PARAMETERS

phi_point = ...
    BVAR.phi_mean;


Sigma_point = ...
    BVAR.SIGMA_mean;


e_point = ...
    BVAR.e_mean;


[B_point,flag] = ...
    chol( ...
        Sigma_point, ...
        'lower');


assert( ...
    flag == 0, ...
    'Posterior-mean covariance matrix is not positive definite.');


%% ================================================================
% 10. POSTERIOR-MEAN HISTORICAL DECOMPOSITION
%% ================================================================

HD_point = ...
    historical_decomposition( ...
        phi_point, ...
        e_point, ...
        B_point);


HDrtwi_point = ...
    HD_point{shock_er};


%% ================================================================
% 11. POSTERIOR-MEAN NO-SHOCK BASELINE
%% ================================================================

baseline_point = ...
    constructVARBaseline( ...
        phi_point, ...
        y, ...
        p);


%% ================================================================
% 12. GROUP STRUCTURAL CONTRIBUTIONS
%
% Columns:
%
% 1 Global activity
% 2 Commodity prices
% 3 VIX / global risk
% 4 Domestic macro = AU GDP + inflation
% 5 Relative yields
% 6 Other exchange-rate shock
%% ================================================================

HD_grouped_point = [ ...
    HDrtwi_point(:,shock_us) ...
    HDrtwi_point(:,shock_comm) ...
    HDrtwi_point(:,shock_vix) ...
    HDrtwi_point(:,shock_augdp) ...
        + HDrtwi_point(:,shock_inf) ...
    HDrtwi_point(:,shock_spread) ...
    HDrtwi_point(:,shock_er)];


%% ================================================================
% 13. POINT CONTRIBUTIONS OVER 2025Q4-2026Q2
%
% PointContrib columns:
%
% 1 Baseline dynamics
% 2 Global activity
% 3 Commodity prices
% 4 VIX
% 5 Domestic macro
% 6 Relative yields
% 7 Other FX
%% ================================================================

PointContrib = ...
    nan(1,7);


%% Baseline

PointContrib(1) = ...
    baseline_point(i1,shock_er) ...
    - baseline_point(i0,shock_er);


%% Structural shocks

PointContrib(2:7) = ...
    HD_grouped_point(i1,:) ...
    - HD_grouped_point(i0,:);


%% Accounting

PointError = ...
    ActualChange ...
    - sum(PointContrib);


fprintf('\n');
fprintf('Posterior-mean-model accounting error: %.3e\n', ...
    PointError);


assert( ...
    abs(PointError) < 1e-8, ...
    'Posterior-mean point decomposition does not reconstruct RTWI change.');


%% ================================================================
% PART B
% FULL POSTERIOR UNCERTAINTY
%% ================================================================

%% 14. STORAGE
%
% 1 x 7 x posterior draw

EpisodeDraws = ...
    nan( ...
        1, ...
        7, ...
        nDraws);


maxAccountingError = ...
    0;


%% ================================================================
% 15. LOOP THROUGH POSTERIOR DRAWS
%% ================================================================

fprintf('\n');
fprintf('Calculating posterior historical decompositions...\n');


tic;


for ss = 1:nDraws

    %% Parameters

    phi_s = ...
        BVAR.phi_draws(:,:,ss);


    Sigma_s = ...
        BVAR.SIGMA_draws(:,:,ss);


    e_s = ...
        BVAR.e_draws(:,:,ss);


    %% Cholesky impact matrix

    [B_s,flag] = ...
        chol( ...
            Sigma_s, ...
            'lower');


    assert(flag == 0);


    %% Historical decomposition

    HD_s = ...
        historical_decomposition( ...
            phi_s, ...
            e_s, ...
            B_s);


    HDrtwi_s = ...
        HD_s{shock_er};


    %% No-shock baseline for this draw

    baseline_s = ...
        constructVARBaseline( ...
            phi_s, ...
            y, ...
            p);


    %% Group shocks

    grouped_s = [ ...
        HDrtwi_s(:,shock_us) ...
        HDrtwi_s(:,shock_comm) ...
        HDrtwi_s(:,shock_vix) ...
        HDrtwi_s(:,shock_augdp) ...
            + HDrtwi_s(:,shock_inf) ...
        HDrtwi_s(:,shock_spread) ...
        HDrtwi_s(:,shock_er)];


    %% Full-history accounting check

    accounting_s = ...
        y(:,shock_er) ...
        - baseline_s(:,shock_er) ...
        - sum(HDrtwi_s,2);


    maxAccountingError = ...
        max( ...
            maxAccountingError, ...
            max(abs(accounting_s)));


    %% Episode contribution:
    %
    % 2026Q2 minus 2025Q3

    EpisodeDraws(1,1,ss) = ...
        baseline_s(i1,shock_er) ...
        - baseline_s(i0,shock_er);


    EpisodeDraws(1,2:7,ss) = ...
        grouped_s(i1,:) ...
        - grouped_s(i0,:);


    %% Progress

    if mod(ss,1000) == 0

        fprintf( ...
            '  Draw %d of %d\n', ...
            ss, ...
            nDraws);

    end

end


elapsed = ...
    toc;


fprintf( ...
    'Posterior HD calculations completed in %.1f seconds.\n', ...
    elapsed);


fprintf( ...
    'Maximum posterior accounting error: %.3e\n', ...
    maxAccountingError);


