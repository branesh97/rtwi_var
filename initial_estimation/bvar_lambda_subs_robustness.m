        options.ndraws = ...
            robust_ndraws;


        options.burnin = ...
            robust_burnin;


        options.thin = ...
            1;


        options.lambda = ...
            lambda;


        options.decay = ...
            1;


        options.own_lag_prior_mean = [ ...
            0
            1
            0
            0
            0
            0
            1];


        options.intercept_var = ...
            1e6;


        options.sigma_df = ...
            N + 2;


        options.sigma_scale_mult = ...
            1;


        options.stable_only = ...
            true;


        options.max_root = ...
            0.9999;


        options.max_stability_tries = ...
            5000;


        options.store_residuals = ...
            true;


        options.seed = ...
            25000 + ll;


        options.verbose = ...
            false;


        tic;


