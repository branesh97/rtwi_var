            bvar_soe( ...
                y, ...
                p, ...
                n_foreign, ...
                options);


        fprintf('BVAR estimation: %.1f seconds\n',toc);


        tic;


        [FEVD_draws,EpisodeShock_draws] = ...
            computePosteriorObjects( ...
                B, ...
                horFEVD, ...
                episode_i0, ...
                episode_i1);


