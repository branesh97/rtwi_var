    data, ...
    {'NA','N/A','na',''});


if ~isdatetime(data.quarter_start)

    if isnumeric(data.quarter_start)

        data.quarter_start = ...
            datetime( ...
                data.quarter_start, ...
                'ConvertFrom','excel');

    else

        data.quarter_start = ...
            datetime(data.quarter_start);

    end

end


