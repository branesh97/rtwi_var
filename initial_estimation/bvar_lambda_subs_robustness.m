shock_inf = 5;

shock_spread = 6;

shock_er = 7;


%% 5. ROBUSTNESS SETTINGS

lambdaGrid = ...
    [0.10 0.20 0.30];


nLambda = ...
    length(lambdaGrid);


horFEVD = ...
    20;


selectedHorizons = ...
    [1 4 8 12 20];


CI70 = ...
    [0.15 0.85];


CI95 = ...
    [0.025 0.975];


% Light robustness runs for alternative lambdas

robust_ndraws = ...
    3000;


robust_burnin = ...
    2000;


%% 6. HISTORICAL EPISODES
%
% Identical to final baseline HD script.

episodeNames = { ...
    'GFC', ...
    'Commodity-boom appreciation', ...
    'Post-boom depreciation', ...
    'COVID shock', ...
    'COVID rebound', ...
    'Recent period'};


episodeStart = [ ...
    datetime(2008,7,1); ...
    datetime(2009,7,1); ...
    datetime(2013,1,1); ...
    datetime(2020,1,1); ...
    datetime(2020,4,1); ...
    datetime(2022,1,1)];


episodeEnd = [ ...
    datetime(2009,4,1); ...
    datetime(2011,4,1); ...
    datetime(2015,7,1); ...
    datetime(2020,1,1); ...
    datetime(2021,4,1); ...
    datetime(2026,4,1)];


nEpisodes = ...
    length(episodeNames);


episode_i0 = ...
    nan(nEpisodes,1);


episode_i1 = ...
    nan(nEpisodes,1);


episodeActual = ...
    nan(nEpisodes,1);


for ee = 1:nEpisodes

    episode_i0(ee) = ...
        find( ...
            D.quarter_start < episodeStart(ee), ...
            1, ...
            'last');


    episode_i1(ee) = ...
        find( ...
            D.quarter_start <= episodeEnd(ee), ...
            1, ...
            'last');


    episodeActual(ee) = ...
        y(episode_i1(ee),shock_er) ...
        - y(episode_i0(ee),shock_er);

end


