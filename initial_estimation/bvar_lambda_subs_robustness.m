%% ================================================================
% LOCAL FUNCTION
%% ================================================================

function [FEVD_draws,EpisodeShock_draws] = ...
    computePosteriorObjects( ...
    BVAR, ...
    horFEVD, ...
    episode_i0, ...
    episode_i1)

% ================================================================
% Compute only the quantities needed for the light lambda robustness
% exercise.
%
% FEVD_draws:
%       N x horizon x posterior draw
%
% EpisodeShock_draws:
%       episode x 6 components x posterior draw
%
% Components:
%
%       1 global activity
%       2 commodity
%       3 VIX
%       4 domestic macro = AU GDP + inflation
%       5 relative yield
%       6 other FX
%% ================================================================


    [T,N] = ...
        size(BVAR.y);


    nDraws = ...
        size(BVAR.phi_draws,3);


    nEpisodes = ...
        length(episode_i0);


    assert(~isempty(BVAR.e_draws));


    FEVD_draws = ...
        nan( ...
            N, ...
            horFEVD, ...
            nDraws);


    EpisodeShock_draws = ...
        nan( ...
            nEpisodes, ...
            6, ...
            nDraws);


    for ss = 1:nDraws

        phi_s = ...
            BVAR.phi_draws(:,:,ss);


        Sigma_s = ...
            BVAR.SIGMA_draws(:,:,ss);


        e_s = ...
            BVAR.e_draws(:,:,ss);


        [B_s,flag] = ...
            chol( ...
                Sigma_s, ...
                'lower');


        assert(flag == 0);


        %% FEVD

        [~,FEVD_s] = ...
            calculate_IRF_FEVD( ...
                phi_s, ...
                B_s, ...
                horFEVD, ...
                'FEVD');


        FEVD_draws(:,:,ss) = ...
            squeeze( ...
                FEVD_s( ...
                    7, ...
                    :, ...
                    1:horFEVD));


        %% HISTORICAL DECOMPOSITION

        HD_s = ...
            historical_decomposition( ...
                phi_s, ...
                e_s, ...
                B_s);


        HDrtwi = ...
            HD_s{7};


        components = [ ...
            HDrtwi(:,1) ...
            HDrtwi(:,2) ...
            HDrtwi(:,3) ...
            HDrtwi(:,4) + HDrtwi(:,5) ...
            HDrtwi(:,6) ...
            HDrtwi(:,7)];


        for ee = 1:nEpisodes

            i0 = ...
                episode_i0(ee);


            i1 = ...
                episode_i1(ee);


            EpisodeShock_draws(ee,:,ss) = ...
                components(i1,:) ...
                - components(i0,:);

        end

    end

end