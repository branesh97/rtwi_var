    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('SUBSTANTIVE ROBUSTNESS: LAMBDA = %.2f\n',lambda);
    fprintf('============================================================\n');


    %% ------------------------------------------------------------
    % BASELINE LAMBDA = 0.20
    %
