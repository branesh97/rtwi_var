%% 34. IRF BAND-WIDTH DIAGNOSTIC
%
% Compare 95% interval width using:
%
%   all bootstrap draws
% versus
%   stable draws only
%
% If the stable-only width is much smaller, unstable draws are
% materially contributing to sampling uncertainty.


commWidthAll = ...
    comm_CI95(:,2) - ...
