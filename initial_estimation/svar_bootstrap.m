%% ================================================================
%  AUSTRALIAN DOLLAR DRIVERS - SVAR BOOTSTRAP FOR ESSA ARTICLE
%
%  BASELINE MODEL A
%
%  FOREIGN BLOCK
%    1. US real GDP gap
%    2. RBA commodity price index (SDR)
%    3. VIX
%
%  DOMESTIC BLOCK
%    4. Australian real GDP gap
%    5. Australian trimmed mean inflation
%    6. AU-US 2-year yield spread
%    7. Australian real TWI
%
%  Sample: 1995Q1-2026Q2
%  VAR lags: 2
%
%  Identification:
%    Recursive Cholesky
%
%  Bootstrap:
%    Kilian (1998) bootstrap-after-bootstrap
%
%  ARTICLE PRESENTATION:
%    - 70% central interval
%    - 95% central interval
%    - shaded confidence regions
%
%  UNCERTAINTY DIAGNOSTICS:
%    - bootstrap root distribution
%    - comfortably stable / near-unit / unstable draw groups
%    - all-draw vs stable-only confidence intervals
%    - band-width diagnostics by horizon
%
%  IMPORTANT:
%    All bootstrap draws remain in the BASELINE intervals.
%    Stable-only results are diagnostics, not the preferred inference.
%% ================================================================

clear;
clc;
close all;


%% 1. PRELIMINARY

folder = fileparts(mfilename('fullpath'));

addpath(fullfile(folder,'_func'));


filePath = ...
    fullfile(folder,'data','data_collected.xlsx');


figDir = ...
    fullfile(folder,'figures');

if ~exist(figDir,'dir')
    mkdir(figDir);
end


resultDir = ...
    fullfile(folder,'results');

if ~exist(resultDir,'dir')
    mkdir(resultDir);
end


assert(exist('olsvar_soe','file') == 2, ...
    'olsvar_soe.m not found.');

assert(exist('calculate_IRF_FEVD','file') == 2, ...
    'calculate_IRF_FEVD.m not found.');

assert(exist('bootstrap_after_bootstrap_soe','file') == 2, ...
    'bootstrap_after_bootstrap_soe.m not found.');


%% 2. BOOTSTRAP REUSE OPTION
%
% You have already run the 1000 x 1000 bootstrap.
%
% TRUE:
%   load the bootstrap draws saved by the previous svar_bootstrap.m
%
% FALSE:
%   rerun the Kilian bootstrap from scratch

reuse_previous_bootstrap = true;


previousBootstrapFile = ...
    fullfile( ...
        resultDir, ...
        'svar_bootstrap.mat');


%% 3. IMPORT DATA

data = readtable( ...
    filePath, ...
    'Sheet','data', ...
    'VariableNamingRule','preserve');


data = standardizeMissing( ...
    data, ...
    {'NA','N/A','na',''});


%% 4. DATE VARIABLES

dateVars = { ...
    'quarter_start', ...
    'quarter_end'};


for ii = 1:length(dateVars)

    v = dateVars{ii};

    if ~isdatetime(data.(v))

        if isnumeric(data.(v))

            data.(v) = datetime( ...
                data.(v), ...
                'ConvertFrom','excel');

        else

            data.(v) = ...
                datetime(data.(v));

        end

    end

end


%% 5. MAKE OTHER VARIABLES NUMERIC

varNames = ...
    data.Properties.VariableNames;


for jj = 3:width(data)

    v = varNames{jj};

    if ~isnumeric(data.(v))

        data.(v) = ...
            str2double(string(data.(v)));

    end

end


%% 6. YEARLAB

yr = ...
    year(data.quarter_start);

qtr = ...
    ceil(month(data.quarter_start)/3);


yearlab = ...
    yr + (qtr-1)/4;


quarterlab = ...
    string(yr) + "Q" + string(qtr);


%% 7. SAMPLE

sampleStart = ...
    datetime(1995,1,1);

sampleEnd = ...
    datetime(2026,4,1);


sample = ...
    data.quarter_start >= sampleStart & ...
    data.quarter_start <= sampleEnd;


D = ...
    data(sample,:);


yearlab_svar = ...
    yearlab(sample);

quarterlab_svar = ...
    quarterlab(sample);


T = ...
    height(D);


assert(T == 126, ...
    'Unexpected sample size.');


fprintf('\n============================================================\n');
fprintf('SVAR BOOTSTRAP - ESSA ARTICLE VERSION\n');
fprintf('============================================================\n');

fprintf('Sample: %s to %s\n', ...
    char(quarterlab_svar(1)), ...
    char(quarterlab_svar(end)));

fprintf('Observations: %d\n',T);


%% 8. REQUIRED VARIABLES

requiredVars = { ...
    'us_rgdp', ...
    'comm_price', ...
    'vix', ...
    'au_rgdp', ...
    'au_inf_trim', ...
    'au_us_2yr', ...
    'rtwi'};


for ii = 1:length(requiredVars)

    v = requiredVars{ii};

    assert( ...
        ismember(v,D.Properties.VariableNames), ...
        'Missing variable: %s',v);

    assert( ...
        all(isfinite(D.(v))), ...
        'Variable %s contains missing observations.',v);

end


%% 9. TRANSFORM VARIABLES

log_us_gdp = ...
    100*log(D.us_rgdp);

log_comm = ...
    100*log(D.comm_price);

log_vix = ...
    100*log(D.vix);

log_au_gdp = ...
    100*log(D.au_rgdp);

trim_inf = ...
    D.au_inf_trim;

spread_2yr = ...
    D.au_us_2yr;

log_rtwi = ...
    100*log(D.rtwi);


%% 10. QUADRATIC GDP DETRENDING

tt = ...
    (1:T)';


Xtrend = [ ...
    ones(T,1) ...
    tt ...
    tt.^2];


% US GDP

b_us = ...
    Xtrend \ log_us_gdp;

trend_us = ...
    Xtrend*b_us;

us_gdp_gap = ...
    log_us_gdp - trend_us;


% Australian GDP

b_au = ...
    Xtrend \ log_au_gdp;

trend_au = ...
    Xtrend*b_au;

au_gdp_gap = ...
    log_au_gdp - trend_au;


%% 11. BASELINE DATASET

y = [ ...
    us_gdp_gap ...
    log_comm ...
    log_vix ...
    au_gdp_gap ...
    trim_inf ...
    spread_2yr ...
    log_rtwi];


Variables = { ...
    'US Real GDP', ...
    'Commodity Prices', ...
    'VIX', ...
    'Australian Real GDP', ...
    'Trimmed Mean Inflation', ...
    'AU-US 2yr Spread', ...
    'Real TWI'};


N = ...
    size(y,2);


assert(N == 7);
assert(~any(isnan(y(:))));
assert(~any(isinf(y(:))));


%% 12. MODEL SETTINGS

p = 2;

n_foreign = 3;


shock_us = 1;
shock_comm = 2;
shock_vix = 3;
shock_augdp = 4;
shock_inf = 5;
shock_spread = 6;
shock_er = 7;


% Estimation horizons
hor = 24;
hor_fevd = 40;


% Article plotting horizons
%
% Keep estimation longer than what we emphasise visually.

plot_hor_irf = 16;

plot_hor_fevd = 20;


% Normalised presentation shocks

size_comm_shock = 10;       % +10 log points
size_vix_shock = 10;        % +10 log points
size_spread_shock = 1;      % +1 ppt = 100 bp


%% 13. CONFIDENCE INTERVAL SETTINGS
%
% Central 70%:
%   15th to 85th percentile
%
% Central 95%:
%   2.5th to 97.5th percentile

CI70_quantiles = ...
    [0.15 0.85];

CI95_quantiles = ...
    [0.025 0.975];


%% 14. BOOTSTRAP SETTINGS

nboot1 = 1000;

nboot2 = 1000;

rng_seed = 12345;


%% 15. NO DETERMINISTIC CONTROLS

d = ...
    zeros(T,0);


%% 16. ESTIMATE POINT VAR

[phi,gamma,SIGMA,X,e] = ...
    olsvar_soe( ...
        y, ...
        p, ...
        d, ...
        n_foreign);


%% 17. POINT VAR STABILITY

Companion_original = [ ...
    phi(2:end,:)'; ...
    eye(N*(p-1)) zeros(N*(p-1),N)];


root_original = ...
    max(abs(eig(Companion_original)));


fprintf('\nOriginal VAR maximum root: %.4f\n', ...
    root_original);


%% 18. CHOLESKY IDENTIFICATION

[~,cholFlag] = ...
    chol(SIGMA);


assert(cholFlag == 0, ...
    'Point-estimate SIGMA is not positive definite.');


B = ...
    chol(SIGMA,'lower');


%% 19. POINT-ESTIMATE HEADLINE IRFs

resp_comm = ...
    normalizedShockResponse( ...
        phi, ...
        B, ...
        shock_comm, ...
        size_comm_shock, ...
        hor);


resp_vix = ...
    normalizedShockResponse( ...
        phi, ...
        B, ...
        shock_vix, ...
        size_vix_shock, ...
        hor);


resp_spread = ...
    normalizedShockResponse( ...
        phi, ...
        B, ...
        shock_spread, ...
        size_spread_shock, ...
        hor);


rtwi_comm = ...
    resp_comm(shock_er,:)';

rtwi_vix = ...
    resp_vix(shock_er,:)';

rtwi_spread = ...
    resp_spread(shock_er,:)';


%% 20. POINT-ESTIMATE FEVD

[~,FEVD_point] = ...
    calculate_IRF_FEVD( ...
        phi, ...
        B, ...
        hor_fevd, ...
        'FEVD');


rtwi_FEVD_point = ...
    squeeze( ...
        FEVD_point( ...
            shock_er, ...
            :, ...
            :));


%% 21. LOAD EXISTING BOOTSTRAP OR RERUN

if reuse_previous_bootstrap && isfile(previousBootstrapFile)

    fprintf('\n============================================================\n');
    fprintf('LOADING PREVIOUS BOOTSTRAP DRAWS\n');
    fprintf('============================================================\n');


    S = ...
        load( ...
            previousBootstrapFile, ...
            'results_bootstrap');


    R = ...
        S.results_bootstrap;


    % Basic compatibility checks

    assert(R.p == p, ...
        'Saved bootstrap uses a different lag order.');

    assert(R.n_foreign == n_foreign, ...
        'Saved bootstrap uses a different foreign block.');


    nboot1 = ...
        R.nboot1;

    nboot2 = ...
        R.nboot2;

    rng_seed = ...
        R.rng_seed;


    phi_bias_corrected = ...
        R.phi_bias_corrected;

    bias = ...
        R.bias;


    rtwi_comm_boot = ...
        R.rtwi_comm_boot;

    rtwi_vix_boot = ...
        R.rtwi_vix_boot;

    rtwi_spread_boot = ...
        R.rtwi_spread_boot;


    rtwi_FEVD_boot = ...
        R.rtwi_FEVD_boot;


    max_root_boot = ...
        R.max_root_boot;


    unstable_boot = ...
        R.unstable_boot;


    clear S R


    fprintf('Loaded %d second-stage bootstrap draws.\n', ...
        nboot2);


else

    %% ------------------------------------------------------------
    % RUN KILIAN BOOTSTRAP
    %% ------------------------------------------------------------

    fprintf('\n============================================================\n');
    fprintf('RUNNING KILIAN BOOTSTRAP-AFTER-BOOTSTRAP\n');
    fprintf('============================================================\n');


    rng(rng_seed);


    [phi_boot, ...
     SIGMA_boot, ...
     phi_bias_corrected, ...
     bias] = ...
        bootstrap_after_bootstrap_soe( ...
            phi, ...
            gamma, ...
            X, ...
            e, ...
            d, ...
            p, ...
            n_foreign, ...
            nboot1, ...
            nboot2);


    %% STORAGE

    rtwi_comm_boot = ...
        NaN(hor+1,nboot2);

    rtwi_vix_boot = ...
        NaN(hor+1,nboot2);

    rtwi_spread_boot = ...
        NaN(hor+1,nboot2);


    rtwi_FEVD_boot = ...
        NaN(N,hor_fevd+1,nboot2);


    max_root_boot = ...
        NaN(nboot2,1);

    unstable_boot = ...
        false(nboot2,1);


    %% BOOTSTRAP RESPONSES

    for jj = 1:nboot2

        Companion_boot = [ ...
            phi_boot(2:end,:,jj)'; ...
            eye(N*(p-1)) zeros(N*(p-1),N)];


        max_root_boot(jj) = ...
            max(abs(eig(Companion_boot)));


        unstable_boot(jj) = ...
            max_root_boot(jj) >= 1;


        [B_boot,cholFlag] = ...
            chol( ...
                SIGMA_boot(:,:,jj), ...
                'lower');


        if cholFlag ~= 0

            error( ...
                'Bootstrap SIGMA not positive definite at draw %d.', ...
                jj);

        end


        % Commodity

        resp = ...
            normalizedShockResponse( ...
                phi_boot(:,:,jj), ...
                B_boot, ...
                shock_comm, ...
                size_comm_shock, ...
                hor);


        rtwi_comm_boot(:,jj) = ...
            resp(shock_er,:)';


        % VIX

        resp = ...
            normalizedShockResponse( ...
                phi_boot(:,:,jj), ...
                B_boot, ...
                shock_vix, ...
                size_vix_shock, ...
                hor);


        rtwi_vix_boot(:,jj) = ...
            resp(shock_er,:)';


        % Spread

        resp = ...
            normalizedShockResponse( ...
                phi_boot(:,:,jj), ...
                B_boot, ...
                shock_spread, ...
                size_spread_shock, ...
                hor);


        rtwi_spread_boot(:,jj) = ...
            resp(shock_er,:)';


        % FEVD

        [~,FEVD_j] = ...
            calculate_IRF_FEVD( ...
                phi_boot(:,:,jj), ...
                B_boot, ...
                hor_fevd, ...
                'FEVD');


        rtwi_FEVD_boot(:,:,jj) = ...
            squeeze( ...
                FEVD_j( ...
                    shock_er, ...
                    :, ...
                    :));


        if mod(jj,100) == 0

            fprintf('Completed draw %d of %d\n', ...
                jj,nboot2);

        end

    end

end


%% 22. BIAS-CORRECTED ROOT

Companion_bc = [ ...
    phi_bias_corrected(2:end,:)'; ...
    eye(N*(p-1)) zeros(N*(p-1),N)];


root_bc = ...
    max(abs(eig(Companion_bc)));


%% 23. EFFECTIVE BIAS-CORRECTION SHRINKAGE
%
% bootstrap_after_bootstrap_soe internally uses:
%
% phi_bc = phi + delta*bias
%
% We can infer delta from the returned matrices.

validBias = ...
    abs(bias) > 1e-10;


delta_values = ...
    ( ...
    phi_bias_corrected(validBias) ...
    - phi(validBias) ...
    ) ./ ...
    bias(validBias);


delta_values = ...
    delta_values(isfinite(delta_values));


delta_effective = ...
    median(delta_values);


fprintf('\n============================================================\n');
fprintf('BIAS-CORRECTION DIAGNOSTICS\n');
fprintf('============================================================\n');

fprintf('Original VAR root:          %.4f\n', ...
    root_original);

fprintf('Bias-corrected VAR root:    %.4f\n', ...
    root_bc);

fprintf('Effective shrinkage delta:  %.4f\n', ...
    delta_effective);

fprintf('Maximum absolute raw bias:  %.4f\n', ...
    max(abs(bias(:))));


%% 24. CLASSIFY BOOTSTRAP ROOTS
%
% These groups are diagnostic only.
%
% Comfortable:
%   root < 0.99
%
% Near-unit but stable:
%   0.99 <= root < 1
%
% Unstable:
%   root >= 1

comfortableMask = ...
    max_root_boot < 0.99;


nearUnitMask = ...
    max_root_boot >= 0.99 & ...
    max_root_boot < 1;


unstableMask = ...
    max_root_boot >= 1;


stableMask = ...
    max_root_boot < 1;


nComfortable = ...
    sum(comfortableMask);

nNearUnit = ...
    sum(nearUnitMask);

nUnstable = ...
    sum(unstableMask);

nStable = ...
    sum(stableMask);


fprintf('\n============================================================\n');
fprintf('BOOTSTRAP ROOT GROUPS\n');
fprintf('============================================================\n');

fprintf('Comfortably stable (<0.99):     %d (%.1f%%)\n', ...
    nComfortable, ...
    100*nComfortable/nboot2);

fprintf('Near-unit stable [0.99,1):      %d (%.1f%%)\n', ...
    nNearUnit, ...
    100*nNearUnit/nboot2);

fprintf('Unstable (>=1):                 %d (%.1f%%)\n', ...
    nUnstable, ...
    100*nUnstable/nboot2);


%% 25. ROOT QUANTILES

