    7;


Episode_point = ...
    nan(nEpisodes,nBasicComponents);


for ee = 1:nEpisodes

    i0 = ...
        episode_i0(ee);


    i1 = ...
        episode_i1(ee);


    Episode_point(ee,1) = ...
        rtwi_baseline_point(i1) ...
        - rtwi_baseline_point(i0);


    Episode_point(ee,2:7) = ...
        HD_grouped_point(i1,:) ...
        - HD_grouped_point(i0,:);

end


pointEpisodeError = ...
    episodeActualChange ...
    - sum(Episode_point,2);


assert( ...
    max(abs(pointEpisodeError)) < 1e-8);


%% 25. POSTERIOR EPISODE STORAGE

