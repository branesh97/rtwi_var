%% 26. HD FOR EVERY POSTERIOR DRAW

for ss = 1:nDraws

    phi_s = ...
        BVAR.phi_draws(:,:,ss);


    Sigma_s = ...
        BVAR.SIGMA_draws(:,:,ss);


    e_s = ...
        BVAR.e_draws(:,:,ss);


    [B_s,flag] = ...
        chol( ...
            Sigma_s, ...
            'lower');


    assert(flag == 0);


    HD_s = ...
        historical_decomposition( ...
            phi_s, ...
            e_s, ...
            B_s);


    baseline_s = ...
        constructVARBaseline( ...
            phi_s, ...
            y, ...
            p);


    HDrtwi_s = ...
        HD_s{shock_er};


    grouped_s = [ ...
        HDrtwi_s(:,shock_us) ...
        HDrtwi_s(:,shock_comm) ...
        HDrtwi_s(:,shock_vix) ...
        HDrtwi_s(:,shock_augdp) ...
            + HDrtwi_s(:,shock_inf) ...
        HDrtwi_s(:,shock_spread) ...
        HDrtwi_s(:,shock_er)];


    %% Exact full-sample accounting diagnostic

    err_s = ...
        rtwi_actual ...
        - baseline_s(:,shock_er) ...
        - sum(HDrtwi_s,2);


    maxPosteriorAccountingError = ...
        max( ...
            maxPosteriorAccountingError, ...
            max(abs(err_s)));


    %% Episodes

    for ee = 1:nEpisodes

        i0 = ...
            episode_i0(ee);


        i1 = ...
            episode_i1(ee);


        Episode_draws(ee,1,ss) = ...
            baseline_s(i1,shock_er) ...
            - baseline_s(i0,shock_er);


        Episode_draws(ee,2:7,ss) = ...
            grouped_s(i1,:) ...
            - grouped_s(i0,:);

    end


    if mod(ss,1000) == 0

        fprintf('  HD draw %d of %d\n', ...
            ss,nDraws);

    end

end


