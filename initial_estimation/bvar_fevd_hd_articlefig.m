%% 10. CALCULATE FEVD FOR EVERY POSTERIOR DRAW

tic;


for ss = 1:nDraws

    phi_s = ...
        BVAR.phi_draws(:,:,ss);


    Sigma_s = ...
        BVAR.SIGMA_draws(:,:,ss);


    [B_s,flag] = ...
        chol( ...
            Sigma_s, ...
            'lower');


    assert(flag == 0, ...
        'Sigma draw %d is not positive definite.',ss);


    [~,FEVD_s] = ...
        calculate_IRF_FEVD( ...
            phi_s, ...
            B_s, ...
            horFEVD, ...
            'FEVD');


    rtwiFEVD_s = ...
        squeeze( ...
            FEVD_s( ...
                shock_er, ...
                :, ...
                :));


    % Previous classical scripts use columns 1:H
    % for forecast horizons 1:H.

    FEVD_rtwi_draws(:,:,ss) = ...
        rtwiFEVD_s(:,1:horFEVD);


    if mod(ss,1000) == 0

        fprintf('  FEVD draw %d of %d\n', ...
            ss,nDraws);

    end

end


fprintf('FEVD posterior calculation: %.1f seconds\n',toc);


