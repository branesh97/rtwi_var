%% ================================================================
%  AUSTRALIAN DOLLAR DRIVERS
%  SOE-BVAR: POSTERIOR FEVD AND HISTORICAL DECOMPOSITION
%
%  Baseline BVAR:
%
%    Sample: 1995Q1-2026Q2
%    p = 2
%    lambda = 0.20
%    exact SOE block restriction
%    posterior conditioned on stability
%
%  Main outputs:
%
%    1. RTWI posterior FEVD
%       - posterior median
%       - 70% credible interval
%       - 95% credible interval
%       - optional classical SVAR comparison
%
%    2. Posterior-mean historical decomposition
%       - exact accounting identity
%       - full sample / post-2007
%       - selected historical episodes
%
%    3. Posterior uncertainty around episode contributions
%
%  IMPORTANT:
%
%  The stacked historical decomposition uses the posterior-mean
%  parameter model so that contributions sum exactly.
%
%  Posterior medians and credible intervals are reported separately
%  for episode contributions.
%% ================================================================

