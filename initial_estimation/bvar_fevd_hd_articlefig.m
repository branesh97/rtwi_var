%% 23. EPISODE INDICES

episode_i0 = ...
    nan(nEpisodes,1);


episode_i1 = ...
    nan(nEpisodes,1);


episodeActualChange = ...
    nan(nEpisodes,1);


for ee = 1:nEpisodes

    episode_i0(ee) = ...
        find( ...
            D.quarter_start < episodeStart(ee), ...
            1, ...
            'last');


    episode_i1(ee) = ...
        find( ...
            D.quarter_start <= episodeEnd(ee), ...
            1, ...
            'last');


    episodeActualChange(ee) = ...
        rtwi_actual(episode_i1(ee)) ...
        - rtwi_actual(episode_i0(ee));

end


%% 24. POINT-MODEL EPISODE CONTRIBUTIONS
%
% Columns:
%
% 1 baseline
% 2 global activity
% 3 commodity
% 4 VIX
% 5 domestic macro
% 6 spread
% 7 other FX

