function baseline = ...
    constructVARBaseline( ...
    phi, ...
    y, ...
    p)

% ================================================================
% No-shock VAR path generated by:
%
%   - intercept
%   - initial conditions
%
% Uses the SAME mean-backcasting convention as olsvar and bvar_soe.
%% ================================================================


    [T,N] = ...
        size(y);


    initialMean = ...
        mean(y,1);


    baseline_ext = [ ...
        repmat(initialMean,p,1); ...
        zeros(T,N)];


    for t = 1:T

        thisValue = ...
            phi(1,:);


        for lag = 1:p

            rows = ...
                2 + (lag-1)*N : ...
                1 + lag*N;


            thisValue = ...
                thisValue ...
                + baseline_ext(p+t-lag,:) ...
                * phi(rows,:);

        end


        baseline_ext(p+t,:) = ...
            thisValue;

    end


    baseline = ...
        baseline_ext(p+1:end,:);

end


