%% ================================================================
%  AUSTRALIAN DOLLAR DRIVERS
%  SOE-BVAR IRF CONSISTENCY CHECK
%
%  Purpose:
%
%    Verify that the final stable SOE-BVAR produces economically
%    sensible RTWI responses to the same normalized shocks used in
%    the classical SVAR:
%
%       +10 log-point commodity-price shock
%       +10 log-point VIX shock
%       +100 bp AU-US 2-year spread shock
%
%    Report:
%
%       posterior median
%       central 70% credible interval
%       central 95% credible interval
%       classical SVAR(2) point estimate
%
%    Also verify exact SOE implication:
%
%       a domestic spread shock cannot move the first three
%       foreign variables.
%% ================================================================

clear;
clc;
close all;


%% 1. PATHS

folder = ...
    fileparts(mfilename('fullpath'));

addpath(fullfile(folder,'_func'));


resultDir = ...
    fullfile(folder,'results');

figDir = ...
    fullfile(folder,'figures');


if ~exist(figDir,'dir')
    mkdir(figDir);
end


BVARfile = ...
    fullfile( ...
        resultDir, ...
        'bvar_soe_baseline_lambda020_stable.mat');


assert(isfile(BVARfile), ...
    'Final BVAR file not found.');

assert(exist('calculate_IRF_FEVD','file') == 2, ...
    'calculate_IRF_FEVD.m not found.');


%% 2. LOAD FINAL BVAR

S = ...
    load(BVARfile);


BVAR = ...
    S.BVAR;


clear S


[T,N] = ...
    size(BVAR.y);


p = ...
    BVAR.p;


n_foreign = ...
    BVAR.n_foreign;


nDraws = ...
    size(BVAR.phi_draws,3);


assert(N == 7);
assert(p == 2);
assert(n_foreign == 3);


%% 3. VARIABLE POSITIONS

shock_us = 1;

shock_comm = 2;

shock_vix = 3;

shock_augdp = 4;

shock_inf = 5;

shock_spread = 6;

shock_er = 7;


%% 4. IRF SETTINGS

hor = 24;

plot_hor = 16;


% Same economically-sized shocks as classical SVAR

size_comm_shock = 10;

size_vix_shock = 10;

size_spread_shock = 1;


CI70 = ...
    [0.15 0.85];

CI95 = ...
    [0.025 0.975];


%% 5. STORAGE

rtwi_comm_draws = ...
    nan(hor+1,nDraws);

rtwi_vix_draws = ...
    nan(hor+1,nDraws);

rtwi_spread_draws = ...
    nan(hor+1,nDraws);


% Exact SOE diagnostic

maxForeignResponseSpread = ...
    0;


fprintf('\n============================================================\n');
fprintf('BVAR IRF CONSISTENCY CHECK\n');
fprintf('============================================================\n');

fprintf('Posterior draws: %d\n',nDraws);


%% 6. IRF FOR EVERY POSTERIOR DRAW

tic;


for ss = 1:nDraws

    phi_s = ...
        BVAR.phi_draws(:,:,ss);


    Sigma_s = ...
        BVAR.SIGMA_draws(:,:,ss);


    [B_s,flag] = ...
        chol( ...
            Sigma_s, ...
            'lower');


    assert(flag == 0);


    %% COMMODITY

    resp = ...
        normalizedShockResponse( ...
            phi_s, ...
            B_s, ...
            shock_comm, ...
            size_comm_shock, ...
            hor);


    rtwi_comm_draws(:,ss) = ...
        resp(shock_er,:)';


    %% VIX

    resp = ...
        normalizedShockResponse( ...
            phi_s, ...
            B_s, ...
            shock_vix, ...
            size_vix_shock, ...
            hor);


    rtwi_vix_draws(:,ss) = ...
        resp(shock_er,:)';


    %% SPREAD

    respSpread = ...
        normalizedShockResponse( ...
            phi_s, ...
            B_s, ...
            shock_spread, ...
            size_spread_shock, ...
            hor);


    rtwi_spread_draws(:,ss) = ...
        respSpread(shock_er,:)';


    %% EXACT SOE CHECK

    thisForeignResponse = ...
        max( ...
            abs( ...
                respSpread( ...
                    1:n_foreign, ...
                    :)), ...
            [], ...
            'all');


    maxForeignResponseSpread = ...
        max( ...
            maxForeignResponseSpread, ...
            thisForeignResponse);


    if mod(ss,1000) == 0

        fprintf('  IRF draw %d of %d\n', ...
            ss,nDraws);

    end

end


fprintf('IRF calculations completed in %.1f seconds.\n',toc);


fprintf('\nMaximum foreign response to spread shock = %.3e\n', ...
    maxForeignResponseSpread);


assert( ...
    maxForeignResponseSpread < 1e-10, ...
    'SOE restriction failed in posterior IRFs.');


%% 7. POSTERIOR SUMMARIES

