function response = normalizedShockResponse( ...
    phi, ...
    B, ...
    shockIndex, ...
    shockSize, ...
    hor)

    N = ...
        size(B,1);


    Bn = ...
        B;


    ownImpact = ...
        B(shockIndex,shockIndex);


    if abs(ownImpact) < 1e-12

        error( ...
            'Shock own-impact is effectively zero.');

    end


    Bn(:,shockIndex) = ...
        shockSize ...
        * B(:,shockIndex) ...
        / ownImpact;


    IRF = ...
        calculate_IRF_FEVD( ...
            phi, ...
            Bn, ...
            hor);


    IRF3 = ...
        reshape( ...
            IRF, ...
            N,N,hor+1);


    response = ...
        squeeze( ...
            IRF3(:,shockIndex,:));


    assert( ...
        abs( ...
            response(shockIndex,1) ...
            - shockSize) ...
        < 1e-8);

end


function [h95,h70,hPoint] = plotBands( ...
    x, ...
    point, ...
    ci70, ...
    ci95)

    x = ...
        x(:);

    point = ...
        point(:);


    grey95 = ...
        [0.88 0.88 0.88];

    grey70 = ...
        [0.68 0.68 0.68];


    h95 = fill( ...
        [x;flipud(x)], ...
        [ci95(:,1);flipud(ci95(:,2))], ...
        grey95, ...
        'EdgeColor','none', ...
        'FaceAlpha',0.75);


    hold on;


    h70 = fill( ...
        [x;flipud(x)], ...
        [ci70(:,1);flipud(ci70(:,2))], ...
        grey70, ...
        'EdgeColor','none', ...
        'FaceAlpha',0.85);


    hPoint = plot( ...
        x, ...
        point, ...
        '-k', ...
        'LineWidth',2);


    yline( ...
        0, ...
        'k:', ...
        'HandleVisibility','off');


    grid on;
    box off;

end