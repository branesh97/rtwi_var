%% 28. SELECTED HISTORICAL EPISODES
%
% The historical decomposition at a point in time reflects the
% accumulated effect of past shocks.
%
% For article discussion of an episode, it is often more intuitive to
% ask:
%
%     "Which shocks contributed to the CHANGE in the TWI over this
%      episode?"
%
% We therefore calculate the change in each historical-decomposition
% component from the quarter immediately before the episode to the
% episode end.
%
% These dates are deliberately easy to edit.


episodeNames = { ...
    'GFC', ...
    'Commodity-boom appreciation', ...
    'Post-boom depreciation', ...
    'COVID shock', ...
    'COVID rebound', ...
    'Recent period'};


episodeStart = [ ...
    datetime(2008,7,1); ...
    datetime(2009,7,1); ...
    datetime(2013,1,1); ...
    datetime(2020,1,1); ...
    datetime(2020,4,1); ...
    datetime(2022,1,1)];


episodeEnd = [ ...
    datetime(2009,4,1); ...
    datetime(2011,4,1); ...
    datetime(2015,7,1); ...
    datetime(2020,1,1); ...
    datetime(2021,4,1); ...
    datetime(2026,4,1)];


nEpisodes = ...
    length(episodeNames);


episodeActualChange = ...
    nan(nEpisodes,1);


episodeBaselineChange = ...
    nan(nEpisodes,1);


episodeShockChanges = ...
    nan(nEpisodes,size(HD_grouped,2));


for ee = 1:nEpisodes

    % Quarter immediately BEFORE episode start
    i0 = find( ...
        D.quarter_start < episodeStart(ee), ...
        1, ...
        'last');


    % Episode end
    i1 = find( ...
        D.quarter_start <= episodeEnd(ee), ...
        1, ...
        'last');


    if isempty(i0) || isempty(i1)

        error( ...
            'Episode %s lies outside the model sample.', ...
            episodeNames{ee});

    end


    episodeActualChange(ee) = ...
        rtwi_actual_log(i1) ...
        - rtwi_actual_log(i0);


    episodeBaselineChange(ee) = ...
        rtwi_baseline_log(i1) ...
        - rtwi_baseline_log(i0);


    episodeShockChanges(ee,:) = ...
        HD_grouped(i1,:) ...
        - HD_grouped(i0,:);

end


%% 29. EPISODE ACCOUNTING CHECK

episodeReconstructedChange = ...
    episodeBaselineChange ...
    + sum(episodeShockChanges,2);


episodeError = ...
    episodeActualChange ...
    - episodeReconstructedChange;


assert( ...
    max(abs(episodeError)) < 1e-8);


