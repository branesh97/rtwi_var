function baseline = constructVARBaseline( ...
    phi, ...
    gamma, ...
    D, ...
    y, ...
    p)

% ================================================================
% CONSTRUCTVARBASELINE
%
% Reconstructs the VAR path generated by:
%
%   - intercept
%   - deterministic/exogenous controls
%   - initial conditions
%
% with all reduced-form / structural shocks set to zero.
%
% This function deliberately mirrors the mean-backcasting convention
% used in olsvar_soe.m:
%
%   the p pre-sample observations are set equal to mean(y).
%
% INPUTS
%
% phi:
%   (1+p*N) x N
%
% gamma:
%   q x N
%
% D:
%   T x q
%
% y:
%   T x N actual VAR dataset
%
% p:
%   lag order
%
% OUTPUT
%
% baseline:
%   T x N
%
% ================================================================


    [T,N] = ...
        size(y);


    if isempty(D)

        D = ...
            zeros(T,0);

    end


    if isempty(gamma)

        gamma = ...
            zeros(size(D,2),N);

    end


    %% SAME BACKCAST AS olsvar_soe.m

    initialMean = ...
        mean(y,1);


    baseline_ext = [ ...
        repmat(initialMean,p,1); ...
        zeros(T,N)];


    %% RECURSION

    for t = 1:T


        % Intercept

        thisValue = ...
            phi(1,:);


        % Deterministic controls

        if size(D,2) > 0

            thisValue = ...
                thisValue ...
                + D(t,:)*gamma;

        end


        % VAR lags

        for lag = 1:p

            rows = ...
                2 + (lag-1)*N : ...
                1 + lag*N;


            thisValue = ...
                thisValue ...
                + baseline_ext(p+t-lag,:) ...
                * phi(rows,:);

        end


        baseline_ext(p+t,:) = ...
            thisValue;

    end


    baseline = ...
        baseline_ext(p+1:end,:);

end