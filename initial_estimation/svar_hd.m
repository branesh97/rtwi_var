%% ================================================================
%  AUSTRALIAN DOLLAR DRIVERS - HISTORICAL DECOMPOSITION
%
%  Baseline classical SVAR:
%
%    1. US real GDP gap
%    2. RBA commodity price index
%    3. VIX
%    4. Australian real GDP gap
%    5. Trimmed mean inflation
%    6. AU-US 2-year yield spread
%    7. Real TWI
%
%  Sample: 1995Q1-2026Q2
%  VAR lags: 2
%  Foreign block: first 3 variables
%
%  Identification:
%    Recursive Cholesky
%
%  Historical decomposition:
%    Uses Ben Wong's historical_decomposition.m
%
%  IMPORTANT:
%    Ben's function gives structural-shock contributions.
%    We separately construct the constant/initial-condition baseline
%    so that the historical decomposition exactly reconstructs y.
%
%% ================================================================

clear;
clc;
close all;


%% 1. PRELIMINARY

folder = fileparts(mfilename('fullpath'));

addpath(fullfile(folder,'_func'));


filePath = ...
    fullfile(folder,'data','data_collected.xlsx');


figDir = ...
    fullfile(folder,'figures');

if ~exist(figDir,'dir')
    mkdir(figDir);
end


resultDir = ...
    fullfile(folder,'results');

if ~exist(resultDir,'dir')
    mkdir(resultDir);
end


assert(exist('olsvar_soe','file') == 2, ...
    'olsvar_soe.m not found.');

assert(exist('historical_decomposition','file') == 2, ...
    'historical_decomposition.m not found.');


%% 2. IMPORT DATA

data = readtable( ...
    filePath, ...
    'Sheet','data', ...
    'VariableNamingRule','preserve');


data = standardizeMissing( ...
    data, ...
    {'NA','N/A','na',''});


%% 3. DATE VARIABLES

dateVars = { ...
    'quarter_start', ...
    'quarter_end'};


for ii = 1:length(dateVars)

    v = dateVars{ii};

    if ~isdatetime(data.(v))

        if isnumeric(data.(v))

            data.(v) = datetime( ...
                data.(v), ...
                'ConvertFrom','excel');

        else

            data.(v) = datetime(data.(v));

        end

    end

end


%% 4. MAKE OTHER VARIABLES NUMERIC

varNames = ...
    data.Properties.VariableNames;


for jj = 3:width(data)

    v = varNames{jj};

    if ~isnumeric(data.(v))

        data.(v) = ...
            str2double(string(data.(v)));

    end

end


%% 5. YEAR / QUARTER LABELS

yr = ...
    year(data.quarter_start);

qtr = ...
    ceil(month(data.quarter_start)/3);


yearlab = ...
    yr + (qtr-1)/4;


quarterlab = ...
    string(yr) + "Q" + string(qtr);


%% 6. SAMPLE

sampleStart = ...
    datetime(1995,1,1);

sampleEnd = ...
    datetime(2026,4,1);


sample = ...
    data.quarter_start >= sampleStart & ...
    data.quarter_start <= sampleEnd;


D = ...
    data(sample,:);


yearlab_svar = ...
    yearlab(sample);

quarterlab_svar = ...
    quarterlab(sample);


T = ...
    height(D);


assert(T == 126, ...
    'Unexpected sample length.');


fprintf('\n============================================================\n');
fprintf('SVAR HISTORICAL DECOMPOSITION\n');
fprintf('============================================================\n');

fprintf('Sample: %s to %s\n', ...
    char(quarterlab_svar(1)), ...
    char(quarterlab_svar(end)));

fprintf('T = %d\n',T);


%% 7. CHECK REQUIRED VARIABLES

requiredVars = { ...
    'us_rgdp', ...
    'comm_price', ...
    'vix', ...
    'au_rgdp', ...
    'au_inf_trim', ...
    'au_us_2yr', ...
    'rtwi'};


for ii = 1:length(requiredVars)

    v = requiredVars{ii};

    assert( ...
        ismember(v,D.Properties.VariableNames), ...
        'Missing variable: %s',v);

    assert( ...
        all(isfinite(D.(v))), ...
        'Variable %s has missing observations.',v);

end


%% 8. TRANSFORM VARIABLES
%
% Identical to baseline SVAR.


log_us_gdp = ...
    100*log(D.us_rgdp);

log_comm = ...
    100*log(D.comm_price);

log_vix = ...
    100*log(D.vix);

log_au_gdp = ...
    100*log(D.au_rgdp);

trim_inf = ...
    D.au_inf_trim;

spread_2yr = ...
    D.au_us_2yr;

log_rtwi = ...
    100*log(D.rtwi);


%% 9. QUADRATIC GDP DETRENDING

tt = ...
    (1:T)';


Xtrend = [ ...
    ones(T,1) ...
    tt ...
    tt.^2];


% US GDP

b_us = ...
    Xtrend \ log_us_gdp;

trend_us = ...
    Xtrend*b_us;

us_gdp_gap = ...
    log_us_gdp - trend_us;


% Australian GDP

b_au = ...
    Xtrend \ log_au_gdp;

trend_au = ...
    Xtrend*b_au;

au_gdp_gap = ...
    log_au_gdp - trend_au;


%% 10. BASELINE VAR DATASET

y = [ ...
    us_gdp_gap ...
    log_comm ...
    log_vix ...
    au_gdp_gap ...
    trim_inf ...
    spread_2yr ...
    log_rtwi];


Variables = { ...
    'US Real GDP', ...
    'Commodity Prices', ...
    'VIX', ...
    'Australian Real GDP', ...
    'Trimmed Mean Inflation', ...
    'AU-US 2yr Spread', ...
    'Real TWI'};


N = ...
    size(y,2);


assert(N == 7);


%% 11. MODEL SETTINGS

p = 2;

n_foreign = 3;


shock_us = 1;
shock_comm = 2;
shock_vix = 3;
shock_augdp = 4;
shock_inf = 5;
shock_spread = 6;
shock_er = 7;


% No deterministic controls
d = ...
    zeros(T,0);


%% 12. ESTIMATE BASELINE SOE VAR

[phi,gamma,SIGMA,X,e] = ...
    olsvar_soe( ...
        y, ...
        p, ...
        d, ...
        n_foreign);


%% 13. STABILITY

Companion = [ ...
    phi(2:end,:)'; ...
    eye(N*(p-1)) zeros(N*(p-1),N)];


rootsVAR = ...
    eig(Companion);


maxRoot = ...
    max(abs(rootsVAR));


fprintf('\nMaximum VAR root: %.4f\n', ...
    maxRoot);


%% 14. CHOLESKY IDENTIFICATION

[B,cholFlag] = ...
    chol(SIGMA,'lower');


assert(cholFlag == 0, ...
    'SIGMA is not positive definite.');


%% 15. STRUCTURAL SHOCKS
%
% Reduced-form:
%
%     e_t = B * epsilon_t
%
% Therefore:
%
%     epsilon_t = B^{-1} e_t
%
% Use left division rather than inv(B).


structural_shocks = ...
    (B \ e')';


StructuralShockTable = ...
    array2table( ...
        structural_shocks, ...
        'VariableNames', ...
        matlab.lang.makeValidName(Variables));


StructuralShockTable = ...
    addvars( ...
        StructuralShockTable, ...
        D.quarter_start, ...
        quarterlab_svar, ...
        'Before',1, ...
        'NewVariableNames', ...
        {'Date','Quarter'});


%% 16. BEN'S HISTORICAL DECOMPOSITION
%
% HD is an N x 1 cell array.
%
% HD{ii}:
%
%     T x N
%
% Rows:
%     time
%
% Columns:
%     contribution of each structural shock
%
% Example:
%
% HD{7}(:,2)
%
% = commodity shock contribution to Real TWI.


HD = ...
    historical_decomposition( ...
        phi, ...
        e, ...
        B);


%% 17. CONSTRUCT BASELINE COMPONENT
%
% Ben's HD only contains structural-shock contributions.
%
% We reconstruct the path generated by:
%
%   - VAR constant
%   - deterministic variables, if any
%   - initial conditions
%
% with ALL structural shocks set equal to zero.
%
% Critically, this helper uses the same mean-backcasting convention
% as olsvar_soe.m.


baseline = ...
    constructVARBaseline( ...
        phi, ...
        gamma, ...
        d, ...
        y, ...
        p);


%% 18. EXACT ACCOUNTING CHECK - ALL VARIABLES

reconstructed = ...
    baseline;


for ii = 1:N

    reconstructed(:,ii) = ...
        baseline(:,ii) ...
        + sum(HD{ii},2);

end


accountingError = ...
    y - reconstructed;


maxAccountingError = ...
    max(abs(accountingError),[], 'all');


fprintf('\n============================================================\n');
fprintf('HISTORICAL DECOMPOSITION ACCOUNTING CHECK\n');
fprintf('============================================================\n');

fprintf('Maximum absolute reconstruction error: %.12g\n', ...
    maxAccountingError);


assert( ...
    maxAccountingError < 1e-8, ...
    'Historical decomposition does not reconstruct y exactly.');


fprintf('PASS: baseline + structural shocks reconstruct the data.\n');


%% 19. REAL TWI HISTORICAL DECOMPOSITION
%
% T x N:
%
% contribution of every identified structural shock
% to the level of the Real TWI.


HD_rtwi = ...
    HD{shock_er};


rtwi_baseline_log = ...
    baseline(:,shock_er);


rtwi_actual_log = ...
    y(:,shock_er);


rtwi_reconstructed_log = ...
    reconstructed(:,shock_er);


rtwi_total_shock_component = ...
    sum(HD_rtwi,2);


%% 20. RTWI ACCOUNTING CHECK

rtwiError = ...
    rtwi_actual_log ...
    - rtwi_baseline_log ...
    - rtwi_total_shock_component;


fprintf('\nMaximum Real TWI accounting error: %.12g\n', ...
    max(abs(rtwiError)));


%% 21. ARTICLE-ORIENTED SHOCK GROUPS
%
% Keep the three factors of interest separate:
%
%   Commodity prices
%   Global risk / VIX
%   Relative yields
%
% Group slower macro shocks for readability.
%
% The residual exchange-rate shock remains separate.


HD_global_activity = ...
    HD_rtwi(:,shock_us);


HD_commodity = ...
    HD_rtwi(:,shock_comm);


HD_vix = ...
    HD_rtwi(:,shock_vix);


HD_domestic_macro = ...
    HD_rtwi(:,shock_augdp) ...
    + HD_rtwi(:,shock_inf);


HD_spread = ...
    HD_rtwi(:,shock_spread);


HD_residual_fx = ...
    HD_rtwi(:,shock_er);


HD_grouped = [ ...
    HD_global_activity ...
    HD_commodity ...
    HD_vix ...
    HD_domestic_macro ...
    HD_spread ...
    HD_residual_fx];


groupLabels = { ...
    'Global activity', ...
    'Commodity prices', ...
    'Global risk (VIX)', ...
    'Domestic macro', ...
    'Relative yields', ...
    'Residual FX'};


%% 22. GROUPING ACCOUNTING CHECK

groupingError = ...
    rtwi_total_shock_component ...
    - sum(HD_grouped,2);


assert( ...
    max(abs(groupingError)) < 1e-10);


%% 23. ORDERING-ROBUST PAIR GROUPS
%
% Earlier robustness work showed that swapping recursive order within
% these pairs mainly reallocates their contributions internally.
%
% These grouped series may therefore be useful in the article as
% robustness summaries.


HD_commodity_risk = ...
    HD_commodity ...
    + HD_vix;


HD_yield_fx = ...
    HD_spread ...
    + HD_residual_fx;


%% 24. CONVERT BASELINE / RECONSTRUCTION BACK TO RTWI INDEX
%
% Additivity is exact in 100*log units.
%
% The index versions below are useful only for displaying the implied
% no-shock baseline and checking reconstruction.


rtwi_actual_index = ...
    D.rtwi;


rtwi_baseline_index = ...
    exp(rtwi_baseline_log/100);


rtwi_reconstructed_index = ...
    exp(rtwi_reconstructed_log/100);


maxIndexError = ...
    max(abs( ...
        rtwi_actual_index ...
        - rtwi_reconstructed_index));


fprintf('Maximum reconstructed RTWI-index error: %.12g\n', ...
    maxIndexError);


