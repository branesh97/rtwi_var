%% 27. FEVD BOOTSTRAP CONFIDENCE INTERVALS
%
% Dimensions:
%
% N shocks x (hor_fevd+1) x 4 quantiles

FEVD_CI = ...
    quantile( ...
        rtwi_FEVD_boot, ...
        CI_quantiles, ...
        3);


%% 28. GROUPED FEVD BOOTSTRAP DISTRIBUTIONS
%
% These must be calculated draw by draw BEFORE taking quantiles.
%
% Do not add confidence limits from individual FEVD shares.


comm_vix_point = ...
    rtwi_FEVD_point(shock_comm,:) ...
    + rtwi_FEVD_point(shock_vix,:);


spread_fx_point = ...
    rtwi_FEVD_point(shock_spread,:) ...
    + rtwi_FEVD_point(shock_er,:);


comm_vix_boot = ...
    squeeze( ...
        rtwi_FEVD_boot(shock_comm,:,:) ...
        + rtwi_FEVD_boot(shock_vix,:,:));


spread_fx_boot = ...
    squeeze( ...
        rtwi_FEVD_boot(shock_spread,:,:) ...
        + rtwi_FEVD_boot(shock_er,:,:));


% squeeze gives horizon x bootstrap draw


comm_vix_CI = ...
    quantile( ...
        comm_vix_boot, ...
        CI_quantiles, ...
        2);


spread_fx_CI = ...
    quantile( ...
        spread_fx_boot, ...
        CI_quantiles, ...
        2);


