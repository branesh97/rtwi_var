%% ================================================================
%  AUSTRALIAN DOLLAR DRIVERS - BASELINE SVAR BOOTSTRAP
%
%  Model A:
%
%  FOREIGN BLOCK
%    1. US real GDP gap
%    2. RBA commodity price index (SDR)
%    3. VIX
%
%  DOMESTIC BLOCK
%    4. Australian real GDP gap
%    5. Australian trimmed mean inflation
%    6. AU-US 2-year yield spread
%    7. Australian real TWI
%
%  Sample: 1995Q1-2026Q2
%  VAR lags: 2
%
%  Identification:
%    Recursive Cholesky
%
%  Bootstrap:
%    Kilian (1998) bootstrap-after-bootstrap using
%    bootstrap_after_bootstrap_soe.m
%
%  Outputs:
%    - 85% and 95% bootstrap bands for headline RTWI IRFs
%    - bootstrap FEVD intervals
%    - grouped FEVD intervals
%    - bootstrap stability diagnostics
%% ================================================================

clear;
clc;
close all;


%% 1. PRELIMINARY

folder = fileparts(mfilename('fullpath'));

addpath(fullfile(folder,'_func'));


filePath = ...
    fullfile(folder,'data','data_collected.xlsx');


figDir = ...
    fullfile(folder,'figures');

if ~exist(figDir,'dir')
    mkdir(figDir);
end


resultDir = ...
    fullfile(folder,'results');

if ~exist(resultDir,'dir')
    mkdir(resultDir);
end


assert(exist('olsvar_soe','file') == 2, ...
    'olsvar_soe.m not found.');

assert(exist('calculate_IRF_FEVD','file') == 2, ...
    'calculate_IRF_FEVD.m not found.');

assert(exist('bootstrap_after_bootstrap_soe','file') == 2, ...
    'bootstrap_after_bootstrap_soe.m not found.');


%% 2. IMPORT DATA

data = readtable( ...
    filePath, ...
    'Sheet','data', ...
    'VariableNamingRule','preserve');


data = standardizeMissing( ...
    data, ...
    {'NA','N/A','na',''});


%% 3. DATE VARIABLES

dateVars = { ...
    'quarter_start', ...
    'quarter_end'};


for ii = 1:length(dateVars)

    v = dateVars{ii};

    if ~isdatetime(data.(v))

        if isnumeric(data.(v))

            data.(v) = datetime( ...
                data.(v), ...
                'ConvertFrom','excel');

        else

            data.(v) = ...
                datetime(data.(v));

        end

    end

end


%% 4. MAKE OTHER VARIABLES NUMERIC

varNames = ...
    data.Properties.VariableNames;


for jj = 3:width(data)

    v = varNames{jj};

    if ~isnumeric(data.(v))

        data.(v) = ...
            str2double(string(data.(v)));

    end

end


%% 5. YEARLAB

yr = ...
    year(data.quarter_start);

qtr = ...
    ceil(month(data.quarter_start)/3);


yearlab = ...
    yr + (qtr-1)/4;


quarterlab = ...
    string(yr) + "Q" + string(qtr);


%% 6. SAMPLE

sampleStart = ...
    datetime(1995,1,1);

sampleEnd = ...
    datetime(2026,4,1);


sample = ...
    data.quarter_start >= sampleStart & ...
    data.quarter_start <= sampleEnd;


D = ...
    data(sample,:);

yearlab_svar = ...
    yearlab(sample);

quarterlab_svar = ...
    quarterlab(sample);


T = height(D);


assert(T == 126, ...
    'Unexpected sample size.');


fprintf('\n============================================================\n');
fprintf('BASELINE SVAR BOOTSTRAP\n');
fprintf('============================================================\n');

fprintf('Sample: %s to %s\n', ...
    char(quarterlab_svar(1)), ...
    char(quarterlab_svar(end)));

fprintf('Observations: %d\n',T);


%% 7. CHECK REQUIRED VARIABLES

requiredVars = { ...
    'us_rgdp', ...
    'comm_price', ...
    'vix', ...
    'au_rgdp', ...
    'au_inf_trim', ...
    'au_us_2yr', ...
    'rtwi'};


for ii = 1:length(requiredVars)

    v = requiredVars{ii};

    assert( ...
        ismember(v,D.Properties.VariableNames), ...
        'Missing variable: %s',v);

    assert( ...
        all(isfinite(D.(v))), ...
        'Variable %s contains missing observations.',v);

end


%% 8. TRANSFORM VARIABLES
%
% Same transformations as svar_initial.m


log_us_gdp = ...
    100*log(D.us_rgdp);

log_comm = ...
    100*log(D.comm_price);

log_vix = ...
    100*log(D.vix);

log_au_gdp = ...
    100*log(D.au_rgdp);

trim_inf = ...
    D.au_inf_trim;

spread_2yr = ...
    D.au_us_2yr;

log_rtwi = ...
    100*log(D.rtwi);


%% 9. QUADRATIC GDP DETRENDING

tt = ...
    (1:T)';


Xtrend = [ ...
    ones(T,1) ...
    tt ...
    tt.^2];


% US GDP
b_us = ...
    Xtrend \ log_us_gdp;

trend_us = ...
    Xtrend*b_us;

us_gdp_gap = ...
    log_us_gdp - trend_us;


% Australian GDP
b_au = ...
    Xtrend \ log_au_gdp;

trend_au = ...
    Xtrend*b_au;

au_gdp_gap = ...
    log_au_gdp - trend_au;


%% 10. BASELINE MODEL A DATASET

y = [ ...
    us_gdp_gap ...
    log_comm ...
    log_vix ...
    au_gdp_gap ...
    trim_inf ...
    spread_2yr ...
    log_rtwi];


Variables = { ...
    'US Real GDP', ...
    'Commodity Prices', ...
    'VIX', ...
    'Australian Real GDP', ...
    'Trimmed Mean Inflation', ...
    'AU-US 2yr Spread', ...
    'Real TWI'};


N = ...
    size(y,2);


assert(N == 7);
assert(~any(isnan(y(:))));
assert(~any(isinf(y(:))));


%% 11. MODEL SETTINGS

p = 2;

n_foreign = 3;


shock_us = 1;
shock_comm = 2;
shock_vix = 3;
shock_augdp = 4;
shock_inf = 5;
shock_spread = 6;
shock_er = 7;


hor = 24;

hor_fevd = 40;


% Normalised presentation shocks
size_comm_shock = 10;       % +10 log points
size_vix_shock = 10;        % +10 log points
size_spread_shock = 1;      % +1 ppt = 100 bp


%% 12. BOOTSTRAP SETTINGS

nboot1 = 1000;

nboot2 = 1000;


rng_seed = 12345;


% For a quick code test before the full run, temporarily use:
%
% nboot1 = 100;
% nboot2 = 100;


% 95% and 85% percentile intervals:
%
% col 1 = lower 95
% col 2 = lower 85
% col 3 = upper 85
% col 4 = upper 95

CI_quantiles = ...
    [0.025 0.075 0.925 0.975];


%% 13. NO DETERMINISTIC CONTROLS
%
% IMPORTANT:
%
% bootstrap_after_bootstrap_soe requires d to have T rows even if
% there are zero deterministic variables.
%
% Therefore use zeros(T,0), NOT [].

d = ...
    zeros(T,0);


%% 14. ESTIMATE BASELINE REDUCED-FORM VAR

[phi,gamma,SIGMA,X,e] = ...
    olsvar_soe( ...
        y, ...
        p, ...
        d, ...
        n_foreign);


%% 15. POINT-ESTIMATE STABILITY

Companion_original = [ ...
    phi(2:end,:)'; ...
    eye(N*(p-1)) zeros(N*(p-1),N)];


root_original = ...
    max(abs(eig(Companion_original)));


fprintf('\nOriginal VAR maximum root: %.4f\n', ...
    root_original);


%% 16. POINT-ESTIMATE CHOLESKY

[~,cholFlag] = ...
    chol(SIGMA);


assert(cholFlag == 0, ...
    'Point-estimate SIGMA is not positive definite.');


B = ...
    chol(SIGMA,'lower');


%% 17. POINT-ESTIMATE HEADLINE IRFs

resp_comm = ...
    normalizedShockResponse( ...
        phi, ...
        B, ...
        shock_comm, ...
        size_comm_shock, ...
        hor);


resp_vix = ...
    normalizedShockResponse( ...
        phi, ...
        B, ...
        shock_vix, ...
        size_vix_shock, ...
        hor);


resp_spread = ...
    normalizedShockResponse( ...
        phi, ...
        B, ...
        shock_spread, ...
        size_spread_shock, ...
        hor);


rtwi_comm = ...
    resp_comm(shock_er,:)';

rtwi_vix = ...
    resp_vix(shock_er,:)';

rtwi_spread = ...
    resp_spread(shock_er,:)';


%% 18. POINT-ESTIMATE FEVD
%
% Always use the unnormalised Cholesky B matrix for FEVD.

[~,FEVD_point] = ...
    calculate_IRF_FEVD( ...
        phi, ...
        B, ...
        hor_fevd, ...
        'FEVD');


rtwi_FEVD_point = ...
    squeeze( ...
        FEVD_point( ...
            shock_er, ...
            :, ...
            :));


% Dimensions:
% N shocks x (hor_fevd+1)


%% 19. KILIAN BOOTSTRAP-AFTER-BOOTSTRAP

fprintf('\n============================================================\n');
fprintf('RUNNING KILIAN BOOTSTRAP-AFTER-BOOTSTRAP\n');
fprintf('============================================================\n');

fprintf('First-stage replications:  %d\n',nboot1);
fprintf('Second-stage replications: %d\n',nboot2);


rng(rng_seed);


[phi_boot, ...
 SIGMA_boot, ...
 phi_bias_corrected, ...
 bias] = ...
    bootstrap_after_bootstrap_soe( ...
        phi, ...
        gamma, ...
        X, ...
        e, ...
        d, ...
        p, ...
        n_foreign, ...
        nboot1, ...
        nboot2);


%% 20. BIAS-CORRECTED VAR STABILITY

Companion_bc = [ ...
    phi_bias_corrected(2:end,:)'; ...
    eye(N*(p-1)) zeros(N*(p-1),N)];


root_bc = ...
    max(abs(eig(Companion_bc)));


fprintf('\nBootstrap bias diagnostics:\n');

fprintf('Original VAR maximum root:       %.4f\n', ...
    root_original);

fprintf('Bias-corrected VAR maximum root: %.4f\n', ...
    root_bc);

fprintf('Maximum absolute bias:           %.4f\n', ...
    max(abs(bias(:))));


%% 21. STORAGE FOR BOOTSTRAP IRFs AND FEVD

rtwi_comm_boot = ...
    NaN(hor+1,nboot2);

rtwi_vix_boot = ...
    NaN(hor+1,nboot2);

rtwi_spread_boot = ...
    NaN(hor+1,nboot2);


% RTWI FEVD:
% shock x horizon x bootstrap draw

rtwi_FEVD_boot = ...
    NaN(N,hor_fevd+1,nboot2);


% Stability diagnostics

max_root_boot = ...
    NaN(nboot2,1);

unstable_boot = ...
    false(nboot2,1);


%% 22. BOOTSTRAP IRFs AND FEVD

fprintf('\nConstructing bootstrap IRFs and FEVD...\n');


for jj = 1:nboot2

    %% BOOTSTRAP VAR STABILITY

    Companion_boot = [ ...
        phi_boot(2:end,:,jj)'; ...
        eye(N*(p-1)) zeros(N*(p-1),N)];


    max_root_boot(jj) = ...
        max(abs(eig(Companion_boot)));


    unstable_boot(jj) = ...
        max_root_boot(jj) >= 1;


    %% CHOLESKY IDENTIFICATION

    [B_boot,cholFlag] = ...
        chol( ...
            SIGMA_boot(:,:,jj), ...
            'lower');


    if cholFlag ~= 0

        error( ...
            'Bootstrap covariance matrix not positive definite at draw %d.', ...
            jj);

    end


    %% COMMODITY SHOCK

    resp = ...
        normalizedShockResponse( ...
            phi_boot(:,:,jj), ...
            B_boot, ...
            shock_comm, ...
            size_comm_shock, ...
            hor);


    rtwi_comm_boot(:,jj) = ...
        resp(shock_er,:)';


    %% VIX SHOCK

    resp = ...
        normalizedShockResponse( ...
            phi_boot(:,:,jj), ...
            B_boot, ...
            shock_vix, ...
            size_vix_shock, ...
            hor);


    rtwi_vix_boot(:,jj) = ...
        resp(shock_er,:)';


    %% RELATIVE-YIELD SHOCK

    resp = ...
        normalizedShockResponse( ...
            phi_boot(:,:,jj), ...
            B_boot, ...
            shock_spread, ...
            size_spread_shock, ...
            hor);


    rtwi_spread_boot(:,jj) = ...
        resp(shock_er,:)';


    %% FEVD
    %
    % IMPORTANT:
    % use raw B_boot, not any normalised impact matrix.

    [~,FEVD_j] = ...
        calculate_IRF_FEVD( ...
            phi_boot(:,:,jj), ...
            B_boot, ...
            hor_fevd, ...
            'FEVD');


    rtwi_FEVD_boot(:,:,jj) = ...
        squeeze( ...
            FEVD_j( ...
                shock_er, ...
                :, ...
                :));


    %% PROGRESS

    if mod(jj,100) == 0

        fprintf('Completed bootstrap draw %d of %d\n', ...
            jj,nboot2);

    end

end


%% 23. BOOTSTRAP STABILITY DIAGNOSTICS

unstable_count = ...
    sum(unstable_boot);


fprintf('\n============================================================\n');
fprintf('SECOND-STAGE BOOTSTRAP STABILITY\n');
fprintf('============================================================\n');

fprintf('Unstable draws: %d out of %d (%.1f%%)\n', ...
    unstable_count, ...
    nboot2, ...
    100*unstable_count/nboot2);

fprintf('Median maximum root: %.4f\n', ...
    median(max_root_boot));

fprintf('95th percentile maximum root: %.4f\n', ...
    quantile(max_root_boot,0.95));

fprintf('Maximum maximum root: %.4f\n', ...
    max(max_root_boot));


%% 24. IRF BOOTSTRAP CONFIDENCE INTERVALS

comm_CI = ...
    quantile( ...
        rtwi_comm_boot, ...
        CI_quantiles, ...
        2);


vix_CI = ...
    quantile( ...
        rtwi_vix_boot, ...
        CI_quantiles, ...
        2);


spread_CI = ...
    quantile( ...
        rtwi_spread_boot, ...
        CI_quantiles, ...
        2);


