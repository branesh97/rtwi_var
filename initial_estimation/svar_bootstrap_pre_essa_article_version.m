function response = normalizedShockResponse( ...
    phi, ...
    B, ...
    shockIndex, ...
    shockSize, ...
    hor)

% NORMALIZEDSHOCKRESPONSE
%
% Rescale one structural-shock column so that the shocked variable's
% own impact response equals shockSize.


    N = ...
        size(B,1);


    Bn = ...
        B;


    ownImpact = ...
        B(shockIndex,shockIndex);


    if abs(ownImpact) < 1e-12

        error( ...
            'Shock own-impact is effectively zero.');

    end


    Bn(:,shockIndex) = ...
        shockSize * ...
        B(:,shockIndex) ./ ...
        ownImpact;


    IRF = ...
        calculate_IRF_FEVD( ...
            phi, ...
            Bn, ...
            hor);


    IRF3 = ...
        reshape( ...
            IRF, ...
            N,N,hor+1);


    response = ...
        squeeze( ...
            IRF3(:,shockIndex,:));


    assert( ...
        abs(response(shockIndex,1)-shockSize) < 1e-8);

end


