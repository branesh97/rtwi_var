%% ================================================================
% LOCAL FUNCTION
%% ================================================================

function baseline = constructVARBaseline( ...
    phi, ...
    gamma, ...
    D, ...
    y, ...
    p)

% ================================================================
% Reconstruct VAR path generated by:
%
%   - intercept
%   - deterministic variables
%   - initial conditions
%
% with all shocks equal to zero.
%
% Uses the same mean-backcasting convention as olsvar_soe.m.
% ================================================================


    [T,N] = ...
        size(y);


    if isempty(D)

        D = ...
            zeros(T,0);

    end


    if isempty(gamma)

        gamma = ...
            zeros(size(D,2),N);

    end


    initialMean = ...
        mean(y,1);


    baseline_ext = [ ...
        repmat(initialMean,p,1); ...
        zeros(T,N)];


    for t = 1:T


        % Intercept

        thisValue = ...
            phi(1,:);


        % Deterministic controls

        if size(D,2) > 0

            thisValue = ...
                thisValue ...
                + D(t,:)*gamma;

        end


        % VAR lags

        for lag = 1:p

            rows = ...
                2 + (lag-1)*N : ...
                1 + lag*N;


            thisValue = ...
                thisValue ...
                + baseline_ext(p+t-lag,:) ...
                * phi(rows,:);

        end


        baseline_ext(p+t,:) = ...
            thisValue;

    end


    baseline = ...
        baseline_ext(p+1:end,:);

end